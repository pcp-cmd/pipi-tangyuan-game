const object = value => value !== null && typeof value === 'object' && !Array.isArray(value);
const exact = (value, fields) => object(value) && Object.keys(value).length === fields.length && fields.every(field => Object.hasOwn(value, field));
const proofFields = ['id', 'at', 'passed', 'assisted', 'assessmentVersion', 'codeSha256'];
function independentV8(envelope, id) {
  if (!envelope.game.completed.includes(id)) return false;
  const record = envelope.records[id];
  const candidates = [...(record?.attempts || []), record?.milestones?.independent];
  return candidates.some(proof => exact(proof, proofFields) && typeof proof.id === 'string' && proof.id.length > 0 && proof.id.length <= 100 &&
    Number.isFinite(proof.at) && proof.at >= 0 && proof.passed === true && proof.assisted === false && proof.assessmentVersion === 8 &&
    typeof proof.codeSha256 === 'string' && /^[a-f0-9]{64}$/.test(proof.codeSha256));
}
export function eligibleLegacyAccess(envelope) {
  return Object.keys(LEGACY_ACCESS_ANCESTORS).filter(id => LEGACY_ACCESS_ANCESTORS[id].every(parent => independentV8(envelope, parent)));
}
export function deriveLegacyAccess(envelope, sourceAssessmentVersion) {
  if (![8, 9].includes(sourceAssessmentVersion)) return null;
  const lessonIds = eligibleLegacyAccess(envelope);
  return lessonIds.length ? { policy: LEGACY_ACCESS_POLICY, sourceAssessmentVersion, lessonIds } : null;
}
export function parseLegacyAccess(value, envelope) {
  if (value === null) return null;
  if (!exact(value, ['policy', 'sourceAssessmentVersion', 'lessonIds']) || value.policy !== LEGACY_ACCESS_POLICY ||
      ![8, 9].includes(value.sourceAssessmentVersion) || !Array.isArray(value.lessonIds) || !value.lessonIds.length ||
      new Set(value.lessonIds).size !== value.lessonIds.length) throw new Error('Invalid retained course access.');
  const eligible = eligibleLegacyAccess(envelope);
  if (value.lessonIds.some(id => !eligible.includes(id)) ||
      JSON.stringify(value.lessonIds) !== JSON.stringify(eligible.filter(id => value.lessonIds.includes(id))))
    throw new Error('Retained course access lacks its original prerequisite evidence.');
  return structuredClone(value);
}
export function hasRetainedCourseAccess(envelope, id) {
  const retained = envelope?.legacyAccess;
  if (!retained?.lessonIds?.includes(id)) return false;
  try { return parseLegacyAccess(retained, envelope) !== null; } catch { return false; }
}
