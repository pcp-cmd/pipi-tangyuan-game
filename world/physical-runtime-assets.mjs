export function applyRuntimeSceneAssets(scenes) {
  const result = structuredClone(scenes);
  for (const scene of result) {
    const selected = PHYSICAL_RUNTIME_ASSETS[scene.background];
    if (!selected) continue;
    if (scene.assetSha256 !== selected.originalPng.sha256) throw new Error('Runtime scene art no longer matches its retained original');
    Object.assign(scene, structuredClone(selected));
  }
  return result;
}
